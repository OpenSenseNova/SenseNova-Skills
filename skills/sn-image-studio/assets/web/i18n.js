const languageKey = 'sensenova-image-studio-language';
const supportedLanguages = ['zh-CN', 'en'];
let language = 'zh-CN';

export function initializeLanguage(environment = globalThis) {
  const browserLanguage = environment.navigator?.language?.toLowerCase();
  language = browserLanguage && !browserLanguage.startsWith('zh') ? 'en' : 'zh-CN';
  try {
    const saved = environment.localStorage.getItem(languageKey);
    if (supportedLanguages.includes(saved)) language = saved;
  } catch {}

  const params = new URLSearchParams(environment.location?.search || '');
  const requested = params.get('lang');
  if (supportedLanguages.includes(requested)) {
    language = requested;
    try { environment.localStorage.setItem(languageKey, language); } catch {}
    // Consume the launch preference so a later manual switch survives refresh.
    params.delete('lang');
    const search = params.toString();
    try {
      environment.history.replaceState(environment.history.state, '',
        `${environment.location.pathname}${search ? `?${search}` : ''}${environment.location.hash}`);
    } catch {}
  }
  return language;
}

initializeLanguage();

export function getLanguage() {
  return language;
}

export function setLanguage(next) {
  if (!supportedLanguages.includes(next)) return;
  language = next;
  try { localStorage.setItem(languageKey, language); } catch {}
}

export function t(key, params = {}) {
  const pair = Object.hasOwn(messages, key) ? messages[key] : null;
  return (pair?.[supportedLanguages.indexOf(language)] ?? key)
    .replace(/\{(\w+)\}/g, (match, name) => params?.[name] ?? match);
}

export function localizeDocument(document) {
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = t(element.dataset.i18n);
  });
  for (const attribute of ['aria-label', 'alt', 'content', 'placeholder', 'title']) {
    const source = `data-i18n-${attribute}`;
    document.querySelectorAll(`[${source}]`).forEach(element => {
      element.setAttribute(attribute, t(element.getAttribute(source)));
    });
  }
}
